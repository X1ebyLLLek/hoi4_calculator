def get_equipment_by_category(category: str) -> list[Equipment]:
    """Return all equipment items in a category sorted by year."""
    return sorted(
        [eq for eq in EQUIPMENT_DB.values() if eq.category == category],
        key=lambda e: (e.year, e.tier),
    )


def get_default_equipment_for_year(year: int) -> Dict[str, str]:
    """Return the latest unlocked equipment ID per category for a given tech year."""
    categories = {eq.category for eq in EQUIPMENT_DB.values()}
    result: Dict[str, str] = {}
    for cat in categories:
        candidates = [eq for eq in EQUIPMENT_DB.values() if eq.category == cat and eq.year <= year]
        if not candidates:
            candidates = get_equipment_by_category(cat)
        best = max(candidates, key=lambda e: (e.year, e.tier))
        result[cat] = best.id
    return result
